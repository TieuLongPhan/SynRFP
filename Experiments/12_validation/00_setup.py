#!/usr/bin/env python
"""Step 0. Freeze the environment and build one cache per input policy.

For every policy in study.yaml (raw, n1, n2) this writes

  configs/<policy>.yaml        full experiment config for the existing scripts
  ../work/validation/<policy>/        tables, scaffold groups, split codes, exports
  runs/<policy>/               result root used by the existing scripts

All policies share the same rows, labels, scaffold groups, and split codes.
Groups and splits are computed once from the raw strings (or copied from
../work when the archived caches still exist) and copied to the other
policies, so every comparison across policies is paired on identical splits.
The split codes are also saved under runs/splits/ with checksums.

  python 12_validation/00_setup.py                       # full setup
  python 12_validation/00_setup.py --smoke 600           # tiny end-to-end test setup
  python 12_validation/00_setup.py --rxnfp-python ~/miniconda3/envs/rxnfp/bin/python

--smoke N keeps N reactions per source table and writes everything under
smoke/ instead (configs, work, runs), leaving the real folders untouched.
"""
from __future__ import annotations

import argparse
import copy
import json
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

import vlib as L
from synrfp_exp.config import load_config, log, setup_logging
from synrfp_exp.data import (_synrxn_stamp, dataset_table, export_table, reaction_table,
                             rxn_key)
from synrfp_exp.splits import groups_for, make_split, split_summary


def write_policy_config(base_cfg, base_raw, study, policy, root, n_jobs, datasets=None):
    """configs/<policy>.yaml: the base config with policy paths and validation studies."""
    cfg = copy.deepcopy(base_raw)
    paths = {k: str(v) for k, v in base_cfg["paths"].items() if k != "synrxn_local"}
    paths["work"] = str((root / "work" if root != L.HERE else L.EXP / "work" / "validation") / policy)
    paths["results_root"] = str(root / "runs" / policy)
    cfg["paths"] = paths
    cfg["synrxn"]["local_dir"] = str(base_cfg["paths"]["synrxn_local"])
    cfg["benchmark"]["models"] = study["benchmark"]["models"]
    cfg["benchmark"]["schemes"] = study["benchmark"]["schemes"]
    cfg["benchmark"]["fingerprints"] = study["benchmark"]["fingerprints"]
    cfg["rxnfp_dataset_fingerprints"] = {}       # no dataset-specific checkpoints here
    cfg.get("models", {}).pop("xgb", None)       # XGBoost is not part of this suite
    cfg["clustering"]["fingerprints"] = study["benchmark"]["label_free"]
    cfg["input_policy"] = policy
    if datasets:                                 # restricted runs (smoke tests)
        cfg["datasets"] = {k: v for k, v in cfg["datasets"].items() if k in datasets}
    if n_jobs:
        cfg["n_jobs"] = n_jobs
    out = root / "configs" / f"{policy}.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("# Generated by 12_validation/00_setup.py; do not edit.\n"
                   + yaml.safe_dump(cfg, sort_keys=False))
    return out


def freeze_environment(root, rxnfp_python):
    out = root / "runs" / "environment"
    out.mkdir(parents=True, exist_ok=True)
    (out / "pip_freeze.txt").write_text(L._run([sys.executable, "-m", "pip", "freeze"]))
    (out / "conda_list.txt").write_text(L._run(["conda", "list", "--explicit"]))
    (out / "hardware.txt").write_text(
        L._run(["lscpu"]) + "\n\n" + L._run(["free", "-g"]) + "\n\n"
        + L._run(["nvidia-smi", "--query-gpu=name,memory.total,driver_version",
                  "--format=csv"]))
    if rxnfp_python:
        (out / "rxnfp_pip_freeze.txt").write_text(
            L._run([str(rxnfp_python), "-m", "pip", "freeze"]))
        probe = ("import hashlib,pkg_resources,pathlib,json;"
                 "b=pathlib.Path(pkg_resources.resource_filename('rxnfp','models/transformers'));"
                 "print(json.dumps({str(p.relative_to(b)):hashlib.sha256(p.read_bytes()).hexdigest()"
                 " for p in sorted(b.rglob('*')) if p.is_file() and p.suffix in ('.bin','.json','.txt')}))")
        (out / "rxnfp_checkpoints_sha256.json").write_text(
            L._run([str(rxnfp_python), "-c", probe]))
    (out / "environment.json").write_text(json.dumps(L.environment(), indent=1))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base-config", default=str(L.EXP / "config.yaml"))
    ap.add_argument("--policies", nargs="*")
    ap.add_argument("--datasets", nargs="*")
    ap.add_argument("--n-jobs", type=int)
    ap.add_argument("--smoke", type=int, metavar="N",
                    help="keep N reactions per source table; write under smoke/")
    ap.add_argument("--rxnfp-python", type=Path,
                    help="interpreter of the RXNFP environment, to record its versions")
    args = ap.parse_args()
    setup_logging()
    L.policy_selftest()
    log.info("input-policy self-test passed")

    study = L.study_settings()
    policies = args.policies or study["policies"]
    if "raw" not in policies:
        policies = ["raw"] + policies         # groups and splits come from raw
    root = L.HERE / "smoke" if args.smoke else L.HERE
    base_raw = yaml.safe_load(Path(args.base_config).read_text())
    base_cfg = load_config(args.base_config)
    datasets = args.datasets or list(base_cfg["datasets"])
    keys = list(dict.fromkeys(rxn_key(base_cfg, d) for d in datasets))
    base_work = base_cfg["paths"]["work"]
    freeze_environment(root, args.rxnfp_python)

    cfgs = {}
    for pol in policies:
        path = write_policy_config(base_cfg, base_raw, study, pol, root, args.n_jobs,
                                   args.datasets)
        cfgs[pol] = load_config(path)
        (cfgs[pol]["paths"]["work"] / "tables").mkdir(parents=True, exist_ok=True)
        (cfgs[pol]["paths"]["work"] / "tables" / "SOURCE.json").write_text(
            json.dumps(_synrxn_stamp(cfgs[pol]), indent=1))

    # ---- reaction tables: identical rows, policy-specific reaction strings
    from joblib import Parallel, delayed

    report = []
    for key in keys:
        proto = next(d for d in datasets if rxn_key(base_cfg, d) == key)
        rt = reaction_table(base_cfg, rxn_key(base_cfg, proto)).copy()
        if args.smoke and len(rt) > args.smoke:
            rt = rt.sample(n=args.smoke, random_state=0).sort_index().reset_index(drop=True)
        raw = rt["rxn"].astype(str).tolist()
        for pol in policies:
            cache = cfgs[pol]["paths"]["work"] / "tables" / f"rxn_{key}.pkl"
            if cache.exists():
                continue
            res = Parallel(n_jobs=base_cfg["n_jobs"], batch_size=1024)(
                delayed(L.apply_policy)(s, pol) for s in raw)
            t = rt.copy()
            t["rxn_raw"] = raw
            t["rxn"] = [r[0] for r in res]
            t["policy_status"] = [r[1] for r in res]
            t.to_pickle(cache)
            st = pd.Series([r[1] for r in res]).value_counts().to_dict()
            report.append({"table": key, "policy": pol, "rows": len(t),
                           "changed": int(sum(a != b for a, b in zip(raw, t["rxn"]))),
                           **{f"status_{k}": int(v) for k, v in st.items()}})
            log.info("%s/%s: %s", key, pol, report[-1])

    # ---- dataset tables, groups, splits (from raw), exports
    splits_origin = {}
    snap = root / "runs" / "splits"
    rows = []
    for ds in datasets:
        key = rxn_key(base_cfg, ds)
        raw_cfg = cfgs["raw"]
        raw_work = raw_cfg["paths"]["work"]
        if not args.smoke:      # reuse the archived caches when they still exist
            for sub, name in (("groups", f"{key}.npy"),):
                src, dst = base_work / sub / name, raw_work / sub / name
                if src.exists() and not dst.exists():
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(src, dst)
            src, dst = base_work / "splits" / ds, raw_work / "splits" / ds
            if src.exists() and not dst.exists():
                shutil.copytree(src, dst)
                splits_origin[ds] = "copied from archived work/splits"
        splits_origin.setdefault(ds, "regenerated in this environment")
        try:
            table = dataset_table(raw_cfg, ds)
        except FileNotFoundError as e:
            log.error("%s skipped: %s", ds, e)
            continue
        groups_for(raw_cfg, ds)
        y = table["y"].to_numpy()
        codes = {}
        for scheme, seeds in study["benchmark"]["schemes"].items():
            for seed in seeds:
                codes[f"{scheme}_s{seed}"] = make_split(raw_cfg, ds, scheme, seed)
                rows.append({"dataset": ds, "scheme": scheme, "seed": seed,
                             "records": len(table), "classes": int(table["y"].nunique()),
                             **split_summary(codes[f"{scheme}_s{seed}"], y)})
        snap.mkdir(parents=True, exist_ok=True)
        np.savez_compressed(snap / f"{ds}.npz", **codes)
        for pol in policies:
            work = cfgs[pol]["paths"]["work"]
            if pol != "raw":
                for sub in (Path("groups") / f"{key}.npy", Path("splits") / ds):
                    src, dst = raw_work / sub, work / sub
                    if dst.exists():
                        continue
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    (shutil.copytree if src.is_dir() else shutil.copy2)(src, dst)
            t = dataset_table(cfgs[pol], ds)
            assert len(t) == len(table) and (t["y"].to_numpy() == y).all(), (ds, pol)
            export_table(cfgs[pol], ds, t)
        log.info("%s: tables, groups, splits and exports ready (%s)", ds, splits_origin[ds])

    # ---- raw features can be reused from the archived cache (same strings)
    linked = 0
    if not args.smoke and (base_work / "features").exists():
        for key in keys:
            src = base_work / "features" / key
            dst = cfgs["raw"]["paths"]["work"] / "features" / key
            if not src.exists():
                continue
            dst.mkdir(parents=True, exist_ok=True)
            for f in src.glob("*.npz"):
                if not (dst / f.name).exists():
                    (dst / f.name).symlink_to(f.resolve())
                    linked += 1

    out = root / "runs"
    pd.DataFrame(report).to_csv(out / "setup_policy_report.csv", index=False)
    pd.DataFrame(rows).to_csv(out / "setup_split_summary.csv", index=False)
    info = {"policies": policies, "datasets": datasets, "smoke": args.smoke,
            "splits_origin": splits_origin, "raw_feature_files_linked": linked,
            "split_snapshot_sha256": {p.name: L.sha256(p) for p in sorted(snap.glob("*.npz"))}}
    (out / "setup.json").write_text(json.dumps(info, indent=1))
    L.ROOT, L.RUNS = root, out
    L.write_manifest("00_setup", [out / "setup_policy_report.csv",
                                  out / "setup_split_summary.csv", out / "setup.json"])
    log.info("setup complete: %s", json.dumps({k: info[k] for k in
                                               ("policies", "smoke", "raw_feature_files_linked")}))
    log.info("split origin: %s", splits_origin)


if __name__ == "__main__":
    main()
