#!/usr/bin/env python
"""Canonical-input, ten-seed clustering extension of the frozen validation suite.

Primary all_rows scoring preserves the archived treatment of failed feature
encodings. Optional valid_only/shared_valid runs are separate sensitivity arms.
Missing caches are never generated by this script. --wait-seconds lets a queue
consume completed caches while feature generation continues elsewhere.
"""
from __future__ import annotations

import argparse
import contextlib
import datetime as dt
import fcntl
import hashlib
import json
import os
import resource
import tempfile
import time
from pathlib import Path

import numpy as np
import vlib as L
from sklearn.cluster import KMeans, MiniBatchKMeans
from synrfp_exp import metrics
from synrfp_exp.config import expand_fingerprints, load_config, log, setup_logging
from synrfp_exp.data import dataset_table, reaction_table, rxn_key
from synrfp_exp.features import load
from threadpoolctl import threadpool_limits

SMALL = ["schneider_ub", "schneider_b", "uspto50k_ub", "uspto50k_b",
         "syntemp_r0", "mech_1", "mech_2"]
LARGE = ["tpl_ub", "tpl_b", "ecreact_1", "ecreact_2", "ecreact_3"]
SEEDS = list(range(10))
SMALL_PARAMS = {"n_init": 10, "max_iter": 300, "tol": 0.0001,
                "algorithm": "lloyd", "init": "k-means++"}
LARGE_PARAMS = {"batch_size": 8192, "n_init": 3, "max_iter": 100,
                "reassignment_ratio": 0.01, "init": "k-means++",
                "tol": 0.0, "max_no_improvement": 10, "init_size": None}


def stable_hash(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True,
                                     separators=(",", ":")).encode()).hexdigest()


def atomic_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as fh:
            json.dump(value, fh, indent=1, sort_keys=True)
            fh.write("\n")
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def atomic_npz(path, **arrays):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp.npz", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as fh:
            np.savez_compressed(fh, **arrays)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


@contextlib.contextmanager
def cell_lock(path, blocking=False):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a") as fh:
        try:
            fcntl.flock(fh.fileno(), fcntl.LOCK_EX | (0 if blocking else fcntl.LOCK_NB))
        except BlockingIOError:
            yield False
            return
        try:
            yield True
        finally:
            fcntl.flock(fh.fileno(), fcntl.LOCK_UN)


def feature_path(cfg, dataset, fingerprint):
    return cfg["paths"]["work"] / "features" / rxn_key(cfg, dataset) / f"{fingerprint}.npz"


def required_paths(cfg, dataset, fp, panel, row_policy):
    key = rxn_key(cfg, dataset)
    table = cfg["paths"]["work"] / "tables"
    fps = panel if row_policy == "shared_valid" else [fp]
    return [table / "SOURCE.json", table / f"ds_{dataset}.pkl", table / f"rxn_{key}.pkl",
            *[feature_path(cfg, dataset, f) for f in fps]]


def prepare(cfg, dataset, fp, panel, row_policy, source_hashes):
    ds = dataset_table(cfg, dataset)
    key = rxn_key(cfg, dataset)
    rt = reaction_table(cfg, key)
    rows = ds["row"].to_numpy(dtype=np.int64)
    if len(ds) == 0 or len(np.unique(rows)) != len(rows):
        raise RuntimeError(f"{dataset}: empty dataset or duplicate source-row indexes")
    if not np.array_equal(rt.iloc[rows]["r_id"].astype(str).to_numpy(),
                          ds["r_id"].astype(str).to_numpy()):
        raise RuntimeError(f"{dataset}: dataset/feature row IDs are not aligned")
    if not np.array_equal(rt.iloc[rows]["rxn"].astype(str).to_numpy(),
                          ds["rxn"].astype(str).to_numpy()):
        raise RuntimeError(f"{dataset}: dataset/source reaction strings are not aligned")
    feature = load(cfg, key, fp)
    if len(feature.X) != len(rt) or len(feature.ok) != len(rt):
        raise RuntimeError(f"{dataset}/{fp}: feature/source length mismatch")
    valid = np.asarray(feature.ok[rows], dtype=bool)
    used = np.ones(len(ds), dtype=bool)
    if row_policy == "valid_only":
        used = valid.copy()
    elif row_policy == "shared_valid":
        for other in panel:
            f = feature if other == fp else load(cfg, key, other)
            if len(f.X) != len(rt) or len(f.ok) != len(rt):
                raise RuntimeError(f"{dataset}/{other}: feature/source length mismatch")
            used &= np.asarray(f.ok[rows], dtype=bool)
    k = int(ds["y"].nunique())  # same known-label resolution as archived benchmarks
    if int(used.sum()) < k:
        raise RuntimeError(f"{dataset}/{fp}: {int(used.sum())} usable rows for k={k}")
    X = feature.dense(rows[used])
    if not np.isfinite(X).all():
        raise RuntimeError(f"{dataset}/{fp}: nonfinite feature values")
    if feature.is_bits and not np.isin(X, [0, 1]).all():
        raise RuntimeError(f"{dataset}/{fp}: bit-feature decoding failed")
    provenance = {}
    for path in required_paths(cfg, dataset, fp, panel, row_policy):
        # Files are written atomically upstream; refresh hashes if replaced.
        stamp = (str(path), path.stat().st_size, path.stat().st_mtime_ns)
        if stamp not in source_hashes:
            source_hashes[stamp] = L.sha256(path)
        provenance[str(path)] = source_hashes[stamp]
    return ds, X, valid, used, k, provenance


def scores(ds, spec, labels, used):
    result = {}
    for level in spec.get("hierarchy") or [spec["label"]]:
        column = "label" if level == spec["label"] else level
        result[level] = metrics.clustering(ds.loc[used, column].to_numpy(), labels[used])
    return result


def existing_complete(record_path, assignment_path, expected):
    if not record_path.exists():
        return False  # orphan assignments from an interrupted write can be rebuilt
    record = json.loads(record_path.read_text())
    if record.get("cell_signature") != expected:
        raise RuntimeError(f"Refusing mixed provenance/config on resume: {record_path}")
    if not assignment_path.exists():
        return False
    if record.get("assignment_sha256") != L.sha256(assignment_path):
        raise RuntimeError(f"Assignment checksum differs: {assignment_path}")
    with np.load(assignment_path, allow_pickle=False) as z:
        if not all(key in z.files for key in ("labels", "r_id", "y", "valid", "used", "source_row")):
            return False
        if any(len(z[key]) != record["n_rows"] for key in z.files):
            return False
    return True


def deadline_timestamp(value):
    if value is None:
        return float("inf")
    stamp = dt.datetime.fromisoformat(value)
    if stamp.tzinfo is None:
        raise ValueError("--deadline-utc must include Z or a timezone offset")
    return stamp.timestamp()


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", type=Path, default=L.policy_config_path("n1"))
    ap.add_argument("--mode", choices=["all", "small", "large"], default="all")
    ap.add_argument("--datasets", nargs="+")
    ap.add_argument("--fingerprints", nargs="+")
    ap.add_argument("--seeds", nargs="+", type=int, default=SEEDS)
    ap.add_argument("--threads", type=int, default=4)
    ap.add_argument("--row-policy", choices=["all_rows", "valid_only", "shared_valid"], default="all_rows")
    ap.add_argument("--output", type=Path)
    ap.add_argument("--wait-seconds", type=float, default=0,
                    help="maximum total cache-wait time; process ready datasets first")
    ap.add_argument("--deadline-utc", help="stop between cells at this ISO timestamp; use external timeout for a hard cap")
    ap.add_argument("--list-cells", action="store_true", help="print selected inventory and cache readiness; do no fits")
    args = ap.parse_args()
    if args.threads < 1 or args.wait_seconds < 0 or not set(args.seeds) <= set(SEEDS):
        ap.error("threads must be positive, wait nonnegative, and seeds within 0..9")
    setup_logging()
    cfg = load_config(args.config)
    policy = cfg.get("input_policy", "raw")
    panel = expand_fingerprints(cfg, L.study_settings()["benchmark"]["label_free"])
    fps = expand_fingerprints(cfg, args.fingerprints) if args.fingerprints else panel
    if not set(fps) <= set(panel):
        ap.error("only the frozen five label-free fingerprints are allowed")
    candidates = SMALL + LARGE if args.mode == "all" else SMALL if args.mode == "small" else LARGE
    datasets = args.datasets or candidates
    if not set(datasets) <= set(candidates) or not set(datasets) <= set(cfg["datasets"]):
        ap.error("dataset must be in this mode and the selected config")
    deadline = deadline_timestamp(args.deadline_utc)
    root = args.output or L.RUNS / "clustering" / policy / args.row_policy
    protocol = {"version": 1, "input_policy": policy, "row_policy": args.row_policy,
                "small_datasets": SMALL, "large_datasets": LARGE, "fingerprints": panel,
                "seeds": SEEDS, "small_method": "kmeans", "small_params": SMALL_PARAMS,
                "large_method": "minibatch_kmeans", "large_params": LARGE_PARAMS,
                "k_rule": "number of label classes in the complete endpoint table",
                "normalization": "none", "invalid_encodings": "retained as cached vectors" if args.row_policy == "all_rows" else "excluded; full row-aligned assignments retain -1",
                "config_sha256": L.sha256(args.config), "study_yaml_sha256": L.sha256(L.HERE / "study.yaml"),
                "runner_sha256": L.sha256(Path(__file__)), "environment": L.environment()}
    protocol_hash = stable_hash(protocol)
    inventory = [{"dataset": ds, "fingerprint": fp, "seed": seed,
                  "method": "kmeans" if ds in SMALL else "minibatch_kmeans"}
                 for ds in SMALL + LARGE for fp in panel for seed in SEEDS]
    with cell_lock(root / "protocol.lock", blocking=True):
        path = root / "protocol.json"
        if path.exists() and json.loads(path.read_text()).get("protocol_sha256") != protocol_hash:
            raise RuntimeError(f"Frozen protocol differs: {path}; use a separate output root")
        if not path.exists():
            atomic_json(path, {**protocol, "protocol_sha256": protocol_hash, "inventory": inventory,
                               "expected_cells": len(inventory)})
    pending = [(ds, fp) for ds in datasets for fp in fps]
    if args.list_cells:
        for ds, fp in pending:
            missing = [str(p) for p in required_paths(cfg, ds, fp, panel, args.row_policy) if not p.exists()]
            print(json.dumps({"dataset": ds, "fingerprint": fp, "seeds": args.seeds,
                              "missing": missing}))
        return
    source_hashes = {}
    waited = 0.0
    completed = 0
    while pending and time.time() < deadline:
        progress = False
        for dataset, fp in pending.copy():
            if time.time() >= deadline:
                break
            missing = [p for p in required_paths(cfg, dataset, fp, panel, args.row_policy) if not p.exists()]
            if missing:
                continue
            ds, X, valid, used, k, provenance = prepare(
                cfg, dataset, fp, panel, args.row_policy, source_hashes)
            method = "kmeans" if dataset in SMALL else "minibatch_kmeans"
            params = SMALL_PARAMS if dataset in SMALL else LARGE_PARAMS
            all_done = True
            for seed in args.seeds:
                if time.time() >= deadline:
                    all_done = False
                    break
                signature = stable_hash({"protocol": protocol_hash, "dataset": dataset,
                                         "fingerprint": fp, "seed": seed, "source": provenance})
                stem = root / dataset / fp / f"{method}__s{seed}"
                record_path, assignment_path = stem.with_suffix(".json"), stem.with_suffix(".npz")
                with cell_lock(stem.with_suffix(".lock")) as claimed:
                    if not claimed:
                        all_done = False
                        continue
                    if existing_complete(record_path, assignment_path, signature):
                        completed += 1
                        continue
                    log.info("fit %s %s %s seed=%d rows=%d/%d k=%d threads=%d",
                             policy, dataset, fp, seed, int(used.sum()), len(ds), k, args.threads)
                    started = time.perf_counter()
                    with threadpool_limits(limits=args.threads):
                        model = (KMeans if method == "kmeans" else MiniBatchKMeans)(
                            n_clusters=k, random_state=seed, **params)
                        fitted = model.fit_predict(X)
                    fit_seconds = time.perf_counter() - started
                    labels = np.full(len(ds), -1, dtype=np.int32)
                    labels[used] = fitted
                    score_started = time.perf_counter()
                    score = scores(ds, cfg["datasets"][dataset], labels, used)
                    score_seconds = time.perf_counter() - score_started
                    atomic_npz(assignment_path, labels=labels, valid=valid, used=used,
                               r_id=ds["r_id"].astype(str).to_numpy(dtype=str),
                               y=ds["y"].to_numpy(dtype=np.int32), source_row=ds["row"].to_numpy(dtype=np.int64))
                    record = {"cell_signature": signature, "protocol_sha256": protocol_hash,
                              "dataset": dataset, "fingerprint": fp, "method": method,
                              "seed": seed, "input_policy": policy, "row_policy": args.row_policy,
                              "k": k, "n_rows": len(ds), "n_scored": int(used.sum()),
                              "n_valid": int(valid.sum()), "invalid_rows": int((~valid).sum()),
                              "encoding_coverage": float(valid.mean()), "scoring_coverage": float(used.mean()),
                              "params": params, "threads": args.threads, "scores": score,
                              "fit_seconds": fit_seconds, "score_seconds": score_seconds,
                              "elapsed_seconds": time.perf_counter() - started,
                              "inertia": float(model.inertia_), "n_iter": int(model.n_iter_),
                              "n_steps": int(model.n_steps_) if hasattr(model, "n_steps_") else None,
                              "process_peak_rss_gib": resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / (1024 ** 2),
                              "rss_note": "cumulative process high-water mark, not per-cell allocation",
                              "source_sha256": provenance, "assignment_file": assignment_path.name,
                              "assignment_sha256": L.sha256(assignment_path),
                              "finished_utc": dt.datetime.now(dt.UTC).isoformat()}
                    atomic_json(record_path, record)  # JSON is the completion marker
                    completed += 1
                    progress = True
                    log.info("complete %s/%s s%d: %.1fs AMI=%.4f ARI=%.4f", dataset, fp, seed,
                             fit_seconds, score[cfg["datasets"][dataset]["label"]]["ami"],
                             score[cfg["datasets"][dataset]["label"]]["ari"])
            del X
            if all_done:
                pending.remove((dataset, fp))
                progress = True
        if pending and not progress:
            remaining = min(args.wait_seconds - waited, deadline - time.time())
            if remaining <= 0:
                break
            delay = min(10.0, remaining)
            log.info("waiting for %d feature pairs or claimed cells; %.0fs cache wait remains", len(pending), remaining)
            time.sleep(delay)
            waited += delay
    print(json.dumps({"completed_or_resumed_selected_cells": completed,
                      "selected_cells": len(datasets) * len(fps) * len(args.seeds),
                      "pending_pairs": pending, "cache_wait_seconds": waited,
                      "deadline_reached": time.time() >= deadline, "output": str(root)}))


if __name__ == "__main__":
    main()
